function generateIndonesianAddress(city: string): string {
  const streets = [
    'Jl. Pahlawan', 'Jl. Sudirman', 'Jl. Diponegoro', 'Jl. Pemuda',
    'Jl. Gajah Mada', 'Jl. Ahmad Yani', 'Jl. Sultan Agung',
    'Jl. Majapahit', 'Jl. Hayam Wuruk', 'Jl. Mangkubumi',
  ];
  return `${streets[Math.floor(Math.random() * streets.length)]} No. ${Math.floor(Math.random() * 100) + 1}, ${city}`;
}

function padZero(n: number): string {
  return String(n).padStart(2, '0');
}

