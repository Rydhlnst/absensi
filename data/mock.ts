export const salaries: Salary[] = (() => {
  const result: Salary[] = [];
  const salaryMonths: [number, number][] = [
    [2026, 5],
    [2026, 6],
    [2026, 7],
  ];

  for (const [year, month] of salaryMonths) {
    for (let i = 0; i < employees.length; i++) {
      const emp = employees[i];
      const bonus = emp.position === 'Supervisor' || emp.position === 'Manager' ? 500000 + Math.floor(Math.random() * 500000) : Math.floor(Math.random() * 300000);
      const deduction = Math.floor(Math.random() * 200000);
      const totalSalary = emp.salary + bonus - deduction;
      const statusIndex = i % 3;
      const status: Salary['status'] = statusIndex === 0 ? 'paid' : statusIndex === 1 ? 'processing' : 'pending';

      result.push({
        id: generateId('sal', result.length + 1),
        employeeId: emp.id,
        month,
        year,
        baseSalary: emp.salary,
        bonus,
        deduction,
        totalSalary,
        status,
      });
    }
  }

  return result;
})();

